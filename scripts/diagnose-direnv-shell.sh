#!/usr/bin/env bash
# Source in the ACTUAL interactive Bash to inspect its in-memory prompt hooks.
# Reading this script executes no network requests, uv sync, or Git mutations.
# Usage: source scripts/diagnose-direnv-shell.sh
if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
  echo "REFUSED: run 'source scripts/diagnose-direnv-shell.sh' in your interactive Bash." >&2
  exit 2
fi

echo "=== Direnv: current Bash hook diagnosis (read only) ==="
case $- in
  *i*) echo "Shell: interactive Bash" ;;
  *) echo "Shell: non-interactive; prompt hooks do not execute here" ;;
esac
printf 'Current directory: %s\n' "$PWD"

if declare -F _direnv_hook >/dev/null 2>&1; then
  echo "Direnv Bash function: installed"
else
  echo "Direnv Bash function: MISSING"
fi

# Check declaration only. Never execute arbitrary PROMPT_COMMAND entries.
_prompt_declaration="$(declare -p PROMPT_COMMAND 2>/dev/null || true)"
if [[ -z "$_prompt_declaration" ]]; then
  echo "PROMPT_COMMAND: missing"
elif [[ "$_prompt_declaration" == *"_direnv_hook"* ]]; then
  echo "PROMPT_COMMAND: contains _direnv_hook"
else
  echo "PROMPT_COMMAND: Direnv hook MISSING (other prompt init may have overwritten it)"
fi
# Detect the known malformed token without exposing full PROMPT_COMMAND:
# it may contain user-specific paths or shell commands.
if [[ "$_prompt_declaration" == *"_mise_hookhistory"* ]]; then
  echo "PROMPT_COMMAND: INVALID _mise_hookhistory token detected"
  echo "Expected current mise hook: _mise_hook_prompt_command (if enabled)"
fi
unset _prompt_declaration
# Inspect known prompt sources WITHOUT displaying their contents or running them.
# The invalid name may be generated by PS1 or a prompt function rather than
# appearing directly in PROMPT_COMMAND.
_prompt_bad_source=0
if [[ "${PS1:-}" == *"_mise_hookhistory"* ]]; then
  echo "PS1: INVALID _mise_hookhistory token detected"
  _prompt_bad_source=1
fi
for _prompt_hook_function in \
  _mise_hook_prompt_command \
  _mise_add_prompt_command \
  __starship_prompt_command \
  starship_precmd_user_func \
  _prompt_command; do
  if declare -F "$_prompt_hook_function" >/dev/null 2>&1; then
    _prompt_hook_body="$(declare -f "$_prompt_hook_function" 2>/dev/null || true)"
    if [[ "$_prompt_hook_body" == *"_mise_hookhistory"* ]]; then
      printf 'Prompt function %s: INVALID _mise_hookhistory token detected\n' \
        "$_prompt_hook_function"
      _prompt_bad_source=1
    fi
  fi
done
unset _prompt_hook_body _prompt_hook_function
if [[ $_prompt_bad_source -eq 0 ]]; then
  echo "PS1 / known prompt function bodies: no static _mise_hookhistory token found"
  echo "If Bash still reports it, inspect any custom prompt hook or a stale shell session."
fi
unset _prompt_bad_source

if [[ -n "${DIRENV_DIR:-}" ]]; then
  echo "DIRENV_DIR: present"
else
  echo "DIRENV_DIR: absent (not proof by itself)"
fi

printf 'Expected project venv: %s\n' "$PWD/.venv"
printf 'VIRTUAL_ENV: '
if [[ -n "${VIRTUAL_ENV:-}" ]]; then
  if [[ "$VIRTUAL_ENV" == "$PWD/.venv" ]]; then
    echo "project venv"
  else
    echo "other environment (check your current shell)"
  fi
else
  echo "not set"
fi

for binary in python ansible; do
  target="$(type -P "$binary" 2>/dev/null || true)"
  printf '%s resolves to: %s\n' "$binary" "${target:-MISSING}"
done
unset target binary

if ! command -v direnv >/dev/null 2>&1; then
  echo "Direnv binary: MISSING"
else
  echo "Direnv binary: available"
fi

echo "Direnv exports are applied at the prompt, AFTER the preceding command's output."
echo "If hook is present but VIRTUAL_ENV is absent, check again at the next prompt."
echo "Check this shell's _direnv_hook and PROMPT_COMMAND before modifying it."
echo "For temporary recovery in this shell: eval \"\$(direnv hook bash)\""
echo "Then run _direnv_hook and recheck VIRTUAL_ENV (trusted .envrc only)."
echo "=== End of Direnv hook diagnosis ==="
